import Foundation

enum TeamsRecordingPolicyTests {
    static func run(_ suite: TestSuite) {
        var policy = TeamsRecordingPolicy()
        suite.expect(policy.observe(.present("call-a"), at: 0) == [.offer("call-a")], "call offers recording")
        suite.expect(policy.observe(.present("call-a"), at: 1).isEmpty, "same call offers only once")
        policy.dismiss()
        suite.expect(policy.observe(.present("call-a"), at: 2).isEmpty, "dismissal survives further observations")
        _ = policy.observe(.absent, at: 3)
        _ = policy.observe(.unknown, at: 5)
        _ = policy.observe(.absent, at: 7)
        suite.expect(policy.phase == .dismissed, "unknown breaks the consecutive absence debounce")
        _ = policy.observe(.absent, at: 9)
        suite.expect(policy.phase == .idle, "confirmed absence resets dismissal")
        _ = policy.observe(.present("call-a"), at: 10)
        _ = policy.observe(.unknown, at: 11)
        suite.expect(!policy.accept(at: 11), "observation loss invalidates an open prompt")
        _ = policy.observe(.present("call-a"), at: 12)
        suite.expect(!policy.accept(at: 16), "stale prompt cannot start recording")
        _ = policy.observe(.present("call-a"), at: 17)
        suite.expect(policy.accept(at: 18), "fresh call can start")
        policy.didStart()
        _ = policy.observe(.unknown, at: 19)
        suite.expect(policy.phase == .recording, "AX failure does not end recording")
        _ = policy.observe(.absent, at: 20)
        suite.expect(policy.observe(.absent, at: 22) == [.stop], "two separated absence checks stop recording")
        suite.expect(policy.observe(.absent, at: 24).isEmpty, "finishing is requested exactly once")
        policy.didFinish()
        suite.expect(policy.phase == .idle, "call-end finish permits the next call")
        _ = policy.observe(.present("call-b"), at: 25)
        _ = policy.accept(at: 25)
        suite.expect(policy.requestStop() == [.stop], "stop during asynchronous startup is supported")
        policy.didStart()
        suite.expect(policy.phase == .finishing, "late startup completion cannot resurrect recording")
        policy.didFinish()
        suite.expect(policy.phase == .dismissed, "manual stop suppresses another prompt for this call")
        suite.expect(policy.observe(.present("call-c"), at: 26) == [.offer("call-c")], "different verified call can prompt")
        _ = policy.accept(at: 26)
        policy.didStart()
        suite.expect(policy.observe(.present("call-d"), at: 27) == [.stop], "new call cannot inherit previous capture")
        policy.didFinish()
        suite.expect(policy.observe(.present("call-d"), at: 28) == [.offer("call-d")], "next call waits for old capture to finish")
        suite.expect(policy.observe(.absent, at: 27).isEmpty && policy.phase == .offered, "out-of-order observations are ignored")

        var gate = TeamsMicrophoneGate()
        suite.expect(gate.advance(.unmuted, scanStarted: 0, scanEnded: 0.1) == nil, "first observation cannot release mic audio")
        suite.expect(gate.advance(.unmuted, scanStarted: 1, scanEnded: 1.1) == 0.1...1, "two observations release only the bracketed interval")
        suite.expect(gate.advance(.muted, scanStarted: 2, scanEnded: 2.1) == nil, "mute discards pending mic audio")
        suite.expect(gate.advance(.unmuted, scanStarted: 3, scanEnded: 3.1) == nil, "unmute cannot release earlier muted audio")
        suite.expect(gate.advance(.unknown, scanStarted: 4, scanEnded: 4.1) == nil, "unknown drops the entire interval")
        _ = gate.advance(.unmuted, scanStarted: 5, scanEnded: 5.1)
        suite.expect(gate.advance(.unmuted, scanStarted: 10, scanEnded: 10.1) == nil, "long polling gaps do not authorize mic audio")
        suite.expect(gate.advance(.unmuted, scanStarted: 11, scanEnded: 13) == nil, "slow traversal cannot authorize mic audio")
        suite.expect(gate.advance(.unmuted, scanStarted: .nan, scanEnded: 14) == nil, "invalid clocks close the gate")
    }
}
